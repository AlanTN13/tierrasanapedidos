import { mkdir, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const dir = resolve("app/qa-erp-v3");
const file = resolve(dir, "page.tsx");
const source = `// Generated by scripts/qa-erp-v3.mjs; local fixture only.\nimport { notFound } from "next/navigation";\nimport Fixture from "@/docs/design/erp-v3/qa/page";\nexport default function QA() { if (process.env.NODE_ENV !== "development") notFound(); return <Fixture/>; }\n`;
if (process.argv[2] === "--create") {
  try { await readFile(file); throw new Error("The QA route already exists; remove it before recreating."); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  await mkdir(dir, { recursive: true });
  await writeFile(file, source);
  console.log("Local fixture created at /qa-erp-v3. All submit actions are mocks. Remove before committing.");
} else if (process.argv[2] === "--remove") {
  if (await readFile(file, "utf8") !== source) throw new Error("QA route differs from generated source; inspect before removing.");
  await rm(file);
  await rmdir(dir);
} else throw new Error("Use --create or --remove from the repository root.");
